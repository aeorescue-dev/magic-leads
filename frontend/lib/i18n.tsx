const DICTS: Record<Lang, Dict> = { pt: PT, en: EN, es: ES };

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

const Ctx = createContext<I18nCtx>({
  lang: "pt",
  setLang: () => {},
  t: (k) => k,
});

function getInitialLang(): Lang {
  if (typeof window === "undefined") return "pt";
  const stored = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
  if (stored && LANGS_VALID.includes(stored)) return stored;
  try {
    const nav = (navigator.language || "pt").toLowerCase().slice(0, 2);
    if (LANGS_VALID.includes(nav as Lang)) return nav as Lang;
  } catch {
    /* ignore */
  }
  return "pt";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("pt");

  useEffect(() => {
    setLangState(getInitialLang());
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") {
      window.localStorage.setItem(STORAGE_KEY, l);
    }
  };

  const t = (key: string) => DICTS[lang][key] ?? key;

  return (
    <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
  );
}

export function useI18n() {
  return useContext(Ctx);
}
